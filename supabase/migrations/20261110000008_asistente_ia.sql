-- Registro de preguntas (sirve para el límite diario y para auditoría)
create table public.asistente_consultas (
  id          bigint generated by default as identity primary key,
  usuario_id  uuid not null default auth.uid() references public.usuarios(id) on delete cascade,
  pregunta    text not null check (char_length(pregunta) between 1 and 500),
  herramientas jsonb,
  ok          boolean,
  created_at  timestamptz not null default now()
);
create index on public.asistente_consultas (created_at desc);
create index on public.asistente_consultas (usuario_id);
alter table public.asistente_consultas enable row level security;
revoke all on public.asistente_consultas from anon;

create policy asistente_select on public.asistente_consultas for select to authenticated
  using ((select private.es_supervisor()));
create policy asistente_insert on public.asistente_consultas for insert to authenticated
  with check ((select private.es_supervisor()) and usuario_id = (select auth.uid()));
create policy asistente_update on public.asistente_consultas for update to authenticated
  using (usuario_id = (select auth.uid())) with check (usuario_id = (select auth.uid()));

-- Preguntas hechas hoy (hora de Chile), para el límite diario de la demo
create or replace function public.asistente_consultas_hoy()
returns integer language sql stable set search_path = public as $$
  select count(*)::int from asistente_consultas
   where (created_at at time zone 'America/Santiago')::date = (now() at time zone 'America/Santiago')::date;
$$;

-- Catálogo para que la IA resuelva nombres (grúas, operadores, ítems del checklist)
create or replace function public.asistente_catalogo()
returns json language sql stable set search_path = public as $$
  select json_build_object(
    'gruas', (select json_agg(json_build_object('nombre', nombre, 'modelo', modelo, 'operativa', es_operativa, 'standby', es_standby) order by nombre) from activos),
    'operadores', (select json_agg(json_build_object('nombre', nombre_completo, 'centro_costo', centro_costo, 'cargo', cargo) order by nombre_completo) from usuarios where rol = 'OPERADOR'),
    'categorias', (select json_agg(nombre order by orden) from categorias_plantilla),
    'items_checklist', (select json_agg(p.texto order by c.orden, p.orden) from preguntas_plantilla p join categorias_plantilla c on c.id = p.categoria_id),
    'rango_datos', (select json_build_object('desde', min(timestamp_completado)::date, 'hasta', max(timestamp_completado)::date) from reportes_inspeccion)
  );
$$;

-- Conteos flexibles con agrupación de una lista cerrada (nada de SQL libre)
create or replace function public.asistente_conteo(
  p_agrupar  text default 'ninguno',   -- ninguno | grua | operador | turno | dia | semana | mes | falla | categoria | centro_costo
  p_desde    date default null,
  p_hasta    date default null,
  p_grua     text default null,        -- ej: 'GH-05'
  p_operador text default null,        -- parte del nombre, ej: 'Camila'
  p_turno    integer default null,     -- 1, 2 o 3
  p_item     text default null,        -- parte del texto del ítem, ej: 'freno'
  p_categoria text default null,       -- parte del nombre de categoría, ej: 'Neumáticos'
  p_solo_con_fallas boolean default false
)
returns table (grupo text, inspecciones integer, con_fallas integer, porcentaje_con_fallas numeric,
               items_con_falla integer, score_promedio numeric, horas_uso numeric)
language plpgsql stable set search_path = public as $$
begin
  if p_agrupar not in ('ninguno','grua','operador','turno','dia','semana','mes','falla','categoria','centro_costo') then
    raise exception 'Agrupación no permitida: %', p_agrupar;
  end if;

  return query
  with rep as (
    select r.*, a.nombre as grua, u.nombre_completo as operador, u.centro_costo,
           (r.timestamp_completado at time zone 'America/Santiago')::date as fecha
      from reportes_inspeccion r
      join activos a on a.id = r.activo_id
      join usuarios u on u.id = r.usuario_id
     where (p_desde is null or (r.timestamp_completado at time zone 'America/Santiago')::date >= p_desde)
       and (p_hasta is null or (r.timestamp_completado at time zone 'America/Santiago')::date <= p_hasta)
       and (p_grua is null or a.nombre ilike '%' || p_grua || '%')
       and (p_operador is null or u.nombre_completo ilike '%' || p_operador || '%')
       and (p_turno is null or r.turno = p_turno)
  ), fallas as (
    select rr.reporte_id, p.texto as item, c.nombre as categoria
      from respuestas_reporte rr
      join preguntas_plantilla p on p.id = rr.pregunta_id
      join categorias_plantilla c on c.id = p.categoria_id
     where not rr.respuesta
       and rr.reporte_id in (select id from rep)
       and (p_item is null or p.texto ilike '%' || p_item || '%')
       and (p_categoria is null or c.nombre ilike '%' || p_categoria || '%')
  ), rep_f as (
    -- con filtro de ítem/categoría, "con_fallas" cuenta solo esas fallas
    select rep.*, (select count(*) from fallas f where f.reporte_id = rep.id)::int as n_fallas
      from rep
  ), base as (
    select * from rep_f
     where not p_solo_con_fallas or n_fallas > 0
  )
  select g.grupo, g.inspecciones, g.con_fallas,
         round(100.0 * g.con_fallas / nullif(g.inspecciones, 0), 1),
         g.items_con_falla, g.score, g.horas
    from (
      select case p_agrupar
               when 'grua' then b.grua
               when 'operador' then b.operador
               when 'centro_costo' then coalesce(b.centro_costo, 'Sin centro de costo')
               when 'turno' then 'Turno ' || b.turno
               when 'dia' then b.fecha::text
               when 'semana' then date_trunc('week', b.fecha)::date::text
               when 'mes' then to_char(b.fecha, 'YYYY-MM')
               else 'Total' end as grupo,
             count(*)::int as inspecciones,
             count(*) filter (where b.n_fallas > 0)::int as con_fallas,
             sum(b.n_fallas)::int as items_con_falla,
             round(avg(b.score_cumplimiento)::numeric, 1) as score,
             round(coalesce(sum(b.horas_uso), 0)::numeric, 1) as horas
        from base b
       where p_agrupar not in ('falla', 'categoria')
       group by 1
      union all
      select case p_agrupar when 'falla' then f.item else f.categoria end,
             (select count(*) from base)::int, count(distinct f.reporte_id)::int, count(*)::int, null, null
        from fallas f
        join base b on b.id = f.reporte_id
       where p_agrupar in ('falla', 'categoria')
       group by 1
    ) g
   order by g.items_con_falla desc nulls last, g.inspecciones desc
   limit 60;
end;
$$;

-- Grúas operativas sin ninguna inspección en una fecha
create or replace function public.asistente_gruas_sin_inspeccion(p_fecha date)
returns table (grua text, modelo text, operativa boolean, standby boolean, ultima_inspeccion timestamptz)
language sql stable set search_path = public as $$
  select a.nombre, a.modelo, a.es_operativa, a.es_standby,
         (select max(r.timestamp_completado) from reportes_inspeccion r where r.activo_id = a.id)
    from activos a
   where not exists (select 1 from reportes_inspeccion r
                      where r.activo_id = a.id
                        and (r.timestamp_completado at time zone 'America/Santiago')::date = p_fecha)
   order by a.nombre;
$$;

-- Listado de inspecciones concretas (para citar y enlazar reportes)
create or replace function public.asistente_listar_inspecciones(
  p_desde date default null, p_hasta date default null, p_grua text default null,
  p_operador text default null, p_turno integer default null, p_item text default null,
  p_solo_con_fallas boolean default false, p_limite integer default 10
)
returns table (reporte_id uuid, fecha_hora text, grua text, operador text, turno smallint,
               score numeric, fallas text, horometro_pendiente boolean)
language sql stable set search_path = public as $$
  select r.id, to_char(r.timestamp_completado at time zone 'America/Santiago', 'DD-MM-YYYY HH24:MI'),
         a.nombre, u.nombre_completo, r.turno, r.score_cumplimiento::numeric,
         (select string_agg(p.texto, '; ') from respuestas_reporte rr join preguntas_plantilla p on p.id = rr.pregunta_id
           where rr.reporte_id = r.id and not rr.respuesta),
         r.horometro_pendiente
    from reportes_inspeccion r
    join activos a on a.id = r.activo_id
    join usuarios u on u.id = r.usuario_id
   where (p_desde is null or (r.timestamp_completado at time zone 'America/Santiago')::date >= p_desde)
     and (p_hasta is null or (r.timestamp_completado at time zone 'America/Santiago')::date <= p_hasta)
     and (p_grua is null or a.nombre ilike '%' || p_grua || '%')
     and (p_operador is null or u.nombre_completo ilike '%' || p_operador || '%')
     and (p_turno is null or r.turno = p_turno)
     and (not p_solo_con_fallas or r.tiene_problemas)
     and (p_item is null or exists (select 1 from respuestas_reporte rr join preguntas_plantilla p on p.id = rr.pregunta_id
                                     where rr.reporte_id = r.id and not rr.respuesta and p.texto ilike '%' || p_item || '%'))
   order by r.timestamp_completado desc
   limit least(greatest(coalesce(p_limite, 10), 1), 25);
$$;

