-- Perfiles de usuario (1:1 con auth.users)
create table public.usuarios (
  id              uuid primary key references auth.users(id) on delete cascade,
  nombre_completo text not null,
  rol             text not null check (rol in ('OPERADOR', 'SUPERVISOR')),
  rut             text,
  id_alternativo  text,
  centro_costo    text,
  fecha_ingreso   date,
  cargo           text,
  created_at      timestamptz not null default now()
);

-- Activos físicos (grúas horquilla)
create table public.activos (
  id               integer generated by default as identity primary key,
  nombre           text not null,
  modelo           text not null,
  tipo             text not null default 'Grúa Horquilla',
  codigo_qr        text not null unique,
  es_operativa     boolean not null default true,
  es_standby       boolean not null default false,
  horometro_actual real,
  created_at       timestamptz not null default now()
);

-- Bitácora de cambios operativa / fuera de servicio
create table public.historial_estados_activo (
  id             bigint generated by default as identity primary key,
  activo_id      integer not null references public.activos(id) on delete cascade,
  es_operativa   boolean not null,
  motivo         text,
  usuario_cambio uuid references public.usuarios(id) on delete set null,
  fecha_cambio   timestamptz not null default now()
);
create index on public.historial_estados_activo (activo_id, fecha_cambio desc);
create index on public.historial_estados_activo (usuario_cambio);

-- Plantillas de checklist → categorías → preguntas
create table public.plantillas_checklist (
  id          integer generated by default as identity primary key,
  nombre      text not null,
  tipo_activo text not null default 'Grúa Horquilla',
  activa      boolean not null default true,
  created_at  timestamptz not null default now()
);

create table public.categorias_plantilla (
  id           integer generated by default as identity primary key,
  plantilla_id integer not null references public.plantillas_checklist(id) on delete cascade,
  nombre       text not null,
  orden        integer not null default 0,
  created_at   timestamptz not null default now()
);
create index on public.categorias_plantilla (plantilla_id);

create table public.preguntas_plantilla (
  id             integer generated by default as identity primary key,
  categoria_id   integer not null references public.categorias_plantilla(id) on delete cascade,
  texto          text not null,
  tipo_respuesta text not null default 'SI_NO',
  orden          integer not null default 0,
  created_at     timestamptz not null default now()
);
create index on public.preguntas_plantilla (categoria_id);

-- Reportes de inspección (el id UUID lo genera la app para poder trabajar offline)
create table public.reportes_inspeccion (
  id                     uuid primary key default gen_random_uuid(),
  activo_id              integer not null references public.activos(id),
  usuario_id             uuid not null references public.usuarios(id),
  plantilla_id           integer not null references public.plantillas_checklist(id),
  timestamp_inicio       timestamptz,
  timestamp_completado   timestamptz not null default now(),
  duracion_minutos       integer,
  -- calculados por trigger a partir de respuestas_reporte
  tiene_problemas        boolean not null default false,
  total_respuestas       integer not null default 0,
  respuestas_malas       integer not null default 0,
  score_cumplimiento     real    not null default 100,
  -- horómetro y turno
  turno                  smallint check (turno between 1 and 3),
  horometro_inicial      real,
  horometro_final        real,
  horometro_pendiente    boolean not null default false,
  horas_uso              real,
  horas_uso_omitidas     real,
  observaciones_horometro text,
  created_at             timestamptz not null default now()
);
create index on public.reportes_inspeccion (timestamp_completado desc);
create index on public.reportes_inspeccion (activo_id, timestamp_completado desc);
create index on public.reportes_inspeccion (usuario_id, timestamp_completado desc);
create index on public.reportes_inspeccion (plantilla_id);
create index on public.reportes_inspeccion (horometro_pendiente) where horometro_pendiente;

create table public.respuestas_reporte (
  id          bigint generated by default as identity primary key,
  reporte_id  uuid not null references public.reportes_inspeccion(id) on delete cascade,
  pregunta_id integer not null references public.preguntas_plantilla(id),
  respuesta   boolean not null,           -- true = Bueno / Sí, false = Malo / No
  comentario  text,
  created_at  timestamptz not null default now()
);
create index on public.respuestas_reporte (reporte_id);
create index on public.respuestas_reporte (pregunta_id) where not respuesta;
create index on public.respuestas_reporte (pregunta_id);

create table public.fotos_respuesta (
  id           bigint generated by default as identity primary key,
  respuesta_id bigint not null references public.respuestas_reporte(id) on delete cascade,
  url_storage  text not null,
  created_at   timestamptz not null default now()
);
create index on public.fotos_respuesta (respuesta_id);

-- Tokens de notificaciones push (en la demo se guardan, pero no se envían push)
create table public.fcm_tokens (
  id               uuid primary key default gen_random_uuid(),
  usuario_id       uuid not null references public.usuarios(id) on delete cascade,
  token            text not null,
  dispositivo_info text,
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now()
);
create index on public.fcm_tokens (usuario_id);

-- Destinatarios de correo por grúa
create table public.email_destinatarios (
  id         bigint generated by default as identity primary key,
  email      text not null,
  nombre     text not null,
  activo     boolean not null default true,
  tipo       text not null default 'supervisor',
  created_at timestamptz not null default now()
);

create table public.email_destinatarios_activos (
  id                   bigint generated by default as identity primary key,
  email_destinatario_id bigint not null references public.email_destinatarios(id) on delete cascade,
  activo_id            integer not null references public.activos(id) on delete cascade,
  unique (email_destinatario_id, activo_id)
);
create index on public.email_destinatarios_activos (activo_id);

-- Supervisores que reciben push por grúa
create table public.supervisores_activos (
  id         bigint generated by default as identity primary key,
  usuario_id uuid not null references public.usuarios(id) on delete cascade,
  activo_id  integer not null references public.activos(id) on delete cascade,
  unique (usuario_id, activo_id)
);
create index on public.supervisores_activos (activo_id);

-- NUEVO en la demo: registro de notificaciones simuladas (reemplaza el envío real por Resend/FCM)
create table public.notificaciones_simuladas (
  id          bigint generated by default as identity primary key,
  reporte_id  uuid references public.reportes_inspeccion(id) on delete cascade,
  canal       text not null check (canal in ('EMAIL', 'PUSH')),
  destinatario text not null,
  asunto      text not null,
  detalle     jsonb,
  created_at  timestamptz not null default now()
);
create index on public.notificaciones_simuladas (reporte_id);
